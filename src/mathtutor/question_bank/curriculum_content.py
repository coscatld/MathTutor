def build_reference_questions() -> dict[str, list[dict]]:
    """Build original questions, preserving stable per-point reference ids."""
    result: dict[str, list[dict]] = {}
    for table in (PRIMARY, MIDDLE, HIGH, ADDITIONAL, HIGHER_TASKS):
        for row in table.strip().splitlines():
            fields = row.split("|")
            if len(fields) != 5:
                raise ValueError(f"Invalid question row: {row[:80]}")
            code, stem, answer, explanation, check = fields
            instances = (1,) if table is HIGHER_TASKS else (1, 2)
            for n in instances:
                text, reference_answer, worked, assertion = [expand(s, n) for s in (stem, answer, explanation, check)]
                if len(text) > 300:
                    raise ValueError(f"Question exceeds launch limit: {code}")
                if assertion:
                    left, right = assertion.split("=")
                    if _calculate(left, {}) != _calculate(right, {}):
                        raise ValueError(f"Incorrect authored check {code}: {assertion}")
                items = result.setdefault(code, [])
                if any(q["text"] == text for q in items):
                    raise ValueError(f"Duplicate instances for {code}")
                proof = any(word in text for word in ("证明", "讨论", "反例"))
                difficulty = 3 if table is HIGHER_TASKS or (code.startswith("h3b") and proof) else (2 if code.startswith("h") or n == 2 else 1)
                items.append({
                    "id": f"{code}-ref-{len(items) + 1}", "text": text,
                    "reference_answer": reference_answer, "explanation": worked,
                    "difficulty": difficulty,
                    "category": "推理与证明" if proof else ("综合应用" if table is HIGHER_TASKS else "基础与应用"),
                    "verification": {"mode": "reference", "answer_check": assertion or None,
                                     "student_steps_auto_verified": False},
                })
    return result
