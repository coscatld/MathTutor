"""Original K–12 curriculum questions, authored independently of model output.

The compact rows are question / answer / worked explanation / check expression.
``@...@`` expands small, deterministic integer parameters when building the
bundled JSON. A check is evidence about the supplied answer, never a claim that
student free-form reasoning has been automatically verified.
"""
from __future__ import annotations

import ast
import math
import re
from fractions import Fraction


def _calculate(expression: str, variables: dict):
    """Evaluate our bounded author expressions; never executes Python source."""
    functions = {"frac": Fraction, "gcd": math.gcd, "comb": math.comb, "sum": sum,
                 "min": min, "max": max, "abs": abs, "round": round, "len": len,
                 "decimal": lambda x: f"{float(x):.1f}"}
    def visit(node):
        if isinstance(node, ast.Constant) and isinstance(node.value, (int, float, str)):
            return Fraction(str(node.value)) if isinstance(node.value, float) else node.value
        if isinstance(node, ast.Name) and node.id in variables:
            return variables[node.id]
        if isinstance(node, (ast.List, ast.Tuple)):
            return [visit(n) for n in node.elts]
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -visit(node.operand)
        if isinstance(node, ast.BinOp):
            a, b = visit(node.left), visit(node.right)
            if isinstance(node.op, ast.Add): return a + b
            if isinstance(node.op, ast.Sub): return a - b
            if isinstance(node.op, ast.Mult): return a * b
            if isinstance(node.op, ast.Div): return Fraction(a) / Fraction(b)
            if isinstance(node.op, ast.FloorDiv): return a // b
            if isinstance(node.op, ast.Mod): return a % b
            if isinstance(node.op, ast.Pow) and abs(b) <= 12: return a ** b
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in functions:
            return functions[node.func.id](*[visit(a) for a in node.args])
        raise ValueError(f"Unsupported author expression: {expression}")
    return visit(ast.parse(expression, mode="eval").body)


def expand(text: str, n: int) -> str:
    choices = text.split("~")
    selected = choices[(n - 1) % len(choices)]
    return re.sub(r"@([^@]+)@", lambda m: str(_calculate(m[1], {"n": n})), selected)


