"""Wave 1 item 8 E2E: adaptive practice → verified exercise → child cycle
over the REAL product app (SQLite + WebSocket, §7.5–§7.9).

The live flow is server-driven: a correct attempt advances the cycle
SOLVED →(REFLECTED)→ REFLECTION →(PRACTICE_OFFERED)→ PRACTICE_OFFERED with
a public offer projection (offer id / labels / difficulty / timestamps —
never a solution, answer key, verification log or attestation). The offer
survives restarts, accept binds a child cycle to the EXACT release snapshot,
and judging the child re-uses the same state machine.

These tests were introduced by MAIN INTEGRATION to close the gap where
offers existed in the service layer but were never generated by the live
product flow.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from mathtutor.api.product_app import create_math_tutor_app
from mathtutor.api.product_state import (
    get_product_state,
    reset_product_state,
)
from mathtutor.pedagogy.events import assert_no_forbidden_fields
from mathtutor.security.settings import MathTutorSecuritySettings

pytestmark = pytest.mark.asyncio

_SESSION = "e2e-1"


def _client(db_file: Path) -> TestClient:
    settings = MathTutorSecuritySettings(environment="development", host="127.0.0.1")
    return TestClient(create_math_tutor_app(settings, auth_enabled=False, db_path=str(db_file)))


def _collect(ws) -> list[dict]:
    events: list[dict] = []
    while True:
        frame = json.loads(ws.receive_text())
        events.append(frame)
        if frame.get("event_type") == "turn_end":
            break
    return events


def _committed(events: list[dict]) -> list[dict]:
    return [e for e in events if e.get("event_type") == "tutor_action_committed"]


def _send(ws, command: str, payload: dict, session_id: str = _SESSION) -> None:
    ws.send_text(
        json.dumps(
            {"command": command, "payload": payload, "session_id": session_id},
            ensure_ascii=False,
        )
    )


async def test_full_chain_solve_offer_accept_child_judge(tmp_path: Path) -> None:
    """The complete §7.5 E2E over durable SQLite:
    solve → practice offer → GET /offers → accept → child cycle → judge
    the child against the exact release snapshot → next offer."""
    db_file = tmp_path / "math_tutor.db"
    reset_product_state()

    with _client(db_file) as client:
        # 1. Solve a problem (the seed bank may not cover it — template
        #    fallback through the release gate produces the offer).
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "submit_problem", {"text": "2x + 3 = 7"})
            _collect(ws)
            _send(ws, "submit_attempt", {"answer": "2"})
            events = _collect(ws)
        for frame in events:
            assert_no_forbidden_fields(frame)
        committed = _committed(events)
        assert [c.get("cycle_state") for c in committed] == [
            "solved",
            "practice_offered",
        ]
        offer_event = committed[-1]
        assert offer_event.get("payload", {}).get("action") == "practice_offered"
        extra = offer_event.get("extra", {})
        assert extra.get("offer_id")
        assert extra.get("skill_labels")
        assert extra.get("expires_at")
        assert extra.get("parent_cycle_id")

        # 2. The read API agrees: ONE ACTIVE offer with the same id.
        offers = client.get("/api/v2/math-tutor/offers").json()
        assert len(offers) == 1
        assert offers[0]["status"] == "ACTIVE"
        assert offers[0]["offer_id"] == extra["offer_id"]
        assert offers[0]["difficulty"] in (1, 2, 3, 4, 5)

        # 3. Accept the offer → child cycle starts (practice_started).
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "accept_practice_offer", {"offer_id": extra["offer_id"]})
            events = _collect(ws)
        for frame in events:
            assert_no_forbidden_fields(frame)
        started = [e for e in _committed(events) if e.get("extra", {}).get("child_cycle_id")]
        assert started, "no practice_started event with child cycle id"
        child_cycle_id = started[0]["extra"]["child_cycle_id"]
        assert started[0].get("payload", {}).get("action") == "practice_started"
        # Student-facing problem surface only — never an answer key.
        assert started[0].get("payload", {}).get("problem_latex")
        assert "final_answer" not in json.dumps(events)

        # 4. The offer is consumed; the parent cycle is closed.
        offers = client.get("/api/v2/math-tutor/offers").json()
        assert offers[0]["status"] == "ACCEPTED"
        parent = client.get(
            f"/api/v2/math-tutor/cycles/{extra['parent_cycle_id']}"
        ).json()
        assert parent["state"] == "closed"

        # 5. The child cycle is reachable and judged against the EXACT
        #    release snapshot (same session, same state machine).
        child = client.get(f"/api/v2/math-tutor/cycles/{child_cycle_id}").json()
        assert child["state"] in ("awaiting_attempt", "problem_received")
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "submit_attempt", {"answer": "2"})
            events = _collect(ws)
        for frame in events:
            assert_no_forbidden_fields(frame)
        judged = _committed(events)
        assert judged[0].get("cycle_state") == "solved"
        assert judged[0].get("payload", {}).get("action") == "correct"
        # The child's own solved cycle offers again (server-driven recursion).
        assert judged[-1].get("cycle_state") == "practice_offered"
        assert judged[-1].get("extra", {}).get("offer_id")
        offers = client.get("/api/v2/math-tutor/offers").json()
        assert len(offers) == 2

    reset_product_state()


async def test_duplicate_accept_replays_same_child_cycle(tmp_path: Path) -> None:
    """An already-ACCEPTED offer never opens a second child cycle — the
    replay returns the SAME child id (idempotent replay, §7.7 step 5)."""
    db_file = tmp_path / "math_tutor.db"
    reset_product_state()

    with _client(db_file) as client:
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "submit_problem", {"text": "2x + 3 = 7"})
            _collect(ws)
            _send(ws, "submit_attempt", {"answer": "2"})
            events = _collect(ws)
        offer_id = _committed(events)[-1]["extra"]["offer_id"]

        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "accept_practice_offer", {"offer_id": offer_id})
            first = _collect(ws)
        child_cycle_id = [
            e for e in _committed(first) if e.get("extra", {}).get("child_cycle_id")
        ][0]["extra"]["child_cycle_id"]

        # Second accept: same child cycle, flagged as idempotent replay.
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "accept_practice_offer", {"offer_id": offer_id})
            second = _collect(ws)
        replay = [
            e
            for e in _committed(second)
            if e.get("extra", {}).get("child_cycle_id")
        ][0]
        assert replay["extra"]["child_cycle_id"] == child_cycle_id
        assert replay["extra"].get("idempotent_replay") is True

    reset_product_state()


async def test_offer_flow_survives_restart_between_solve_and_accept(tmp_path: Path) -> None:
    """The offer and the REFLECTED/PRACTICE_OFFERED transitions are durable:
    solve + offer on app instance 1, accept on a fresh instance over the
    SAME database (restart-safe, §7.10)."""
    db_file = tmp_path / "math_tutor.db"
    reset_product_state()

    with _client(db_file) as client:
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "submit_problem", {"text": "2x + 3 = 7"})
            _collect(ws)
            _send(ws, "submit_attempt", {"answer": "2"})
            events = _collect(ws)
        offer_id = _committed(events)[-1]["extra"]["offer_id"]

    # Simulated restart over the same database file.
    reset_product_state()
    with _client(db_file) as client:
        offers = client.get("/api/v2/math-tutor/offers").json()
        assert len(offers) == 1 and offers[0]["offer_id"] == offer_id
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "accept_practice_offer", {"offer_id": offer_id})
            events = _collect(ws)
        child = [
            e for e in _committed(events) if e.get("extra", {}).get("child_cycle_id")
        ]
        assert child, "accept after restart must start the child cycle"

    reset_product_state()


async def test_l5_solution_shown_offers_practice(tmp_path: Path) -> None:
    """The L5 path (solution shown → REFLECTION) also lands on a practice
    offer: 3 hints, then request_solution shows the sanctioned L5 content
    and the cycle advances to PRACTICE_OFFERED (§7.5)."""
    db_file = tmp_path / "math_tutor.db"
    reset_product_state()

    with _client(db_file) as client:
        with client.websocket_connect("/api/v2/math-tutor/ws") as ws:
            _send(ws, "submit_problem", {"text": "2x + 3 = 7"})
            _collect(ws)
            for _ in range(3):  # PRIMARY stage threshold for L5
                _send(ws, "request_hint", {})
                _collect(ws)
            _send(ws, "request_solution", {})
            events = _collect(ws)
        for frame in events:
            assert_no_forbidden_fields(frame)
        committed = _committed(events)
        actions = [e.get("payload", {}).get("action") for e in committed]
        assert "SHOW_SOLUTION" in actions
        assert committed[-1].get("cycle_state") == "practice_offered"
        assert committed[-1].get("extra", {}).get("offer_id")
        offers = client.get("/api/v2/math-tutor/offers").json()
        assert len(offers) == 1 and offers[0]["status"] == "ACTIVE"

    reset_product_state()


class TestMasteryProjectionNormalization:
    """The student-model provider must accept BOTH persisted mastery shapes
    (flat map and the list-of-dicts written by learning.projection) — the
    shape mismatch surfaced only when the live offer flow assembled context
    after an assessed attempt (MAIN INTEGRATION regression)."""

    async def test_list_of_dicts_shape(self) -> None:
        from mathtutor.application.context_assembler import (
            StudentModelSourceProvider,
        )

        async def load_projection(student_id: str) -> dict | None:
            return {
                "estimator_version": "v1",
                "projection_version": 3,
                "concept_mastery": [
                    {"concept_id": "linear-equations", "mastery": 0.62}
                ],
                "skill_mastery": [{"skill_id": "LINEAR_EQUATION", "mastery": 0.51}],
                "active_misconceptions": ["sign-error"],
            }

        provider = StudentModelSourceProvider(load_projection)
        outcome = await provider.load(student_id="s", intent=None, query_hint="")
        ctx = outcome.payload
        assert [e.skill_id for e in ctx.skill_mastery] == ["LINEAR_EQUATION"]
        assert abs(ctx.skill_mastery[0].mastery - 0.51) < 1e-9
        assert [e.skill_id for e in ctx.concept_mastery] == ["linear-equations"]
        assert ctx.active_misconception_rule_ids == ("sign-error",)

    async def test_flat_map_shape(self) -> None:
        from mathtutor.application.context_assembler import (
            StudentModelSourceProvider,
        )

        async def load_projection(student_id: str) -> dict | None:
            return {
                "estimator_version": "v1",
                "projection_version": 1,
                "concept_mastery": {"linear-equations": 0.3},
                "skill_mastery": {"LINEAR_EQUATION": 0.4},
                "active_misconceptions": [],
            }

        provider = StudentModelSourceProvider(load_projection)
        outcome = await provider.load(student_id="s", intent=None, query_hint="")
        ctx = outcome.payload
        assert [e.skill_id for e in ctx.skill_mastery] == ["LINEAR_EQUATION"]
        assert abs(ctx.skill_mastery[0].mastery - 0.4) < 1e-9
