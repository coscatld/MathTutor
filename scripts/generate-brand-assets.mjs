#!/usr/bin/env node
// Run on macOS after npm ci --prefix web; iconutil writes the native ICNS bundle.
import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "web/package.json"));
const sharp = require("sharp");
if (process.platform !== "darwin") {
  throw new Error("Regenerate brand assets on macOS with iconutil. All generated assets are committed for other build platforms.");
}
const svg = await readFile(path.join(root, "resources/branding/mathtutor.svg"), "utf8");
const body = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>")).trim();
async function save(relative, data) {
  const target = path.join(root, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, data);
}
async function png(size) {
  return sharp(Buffer.from(svg), { density: 72 * size / 32 }).resize(size, size).png().toBuffer();
}

// Inline vectors work in both the standalone desktop frontend and GitHub Pages.
const jsx = body.replaceAll("stroke-width", "strokeWidth")
  .replaceAll("stroke-linecap", "strokeLinecap").replaceAll("stroke-linejoin", "strokeLinejoin")
  .replace("<path ", '<path className={animated ? "mt-mark-steps" : undefined} data-loop={loop ? "true" : undefined} style={animated ? { strokeDasharray: 32, ["--len" as string]: 32 } : undefined} ')
  .replace("<circle ", '<circle className={animated ? "mt-mark-goal" : undefined} data-loop={loop ? "true" : undefined} ');
const component = `// Generated by scripts/generate-brand-assets.mjs from resources/branding/mathtutor.svg.
export function BrandMark({ className = "h-8 w-8", animated = false, loop = false }: { className?: string; animated?: boolean; loop?: boolean }) {
  return <svg viewBox="0 0 32 32" fill="none" aria-hidden="true" focusable="false" className={className}>
    ${jsx}
  </svg>;
}
export default BrandMark;
`;
await save("web/components/common/BrandMark.tsx", component);
await save("site/components/brand-mark.tsx", component);
for (const target of ["web/app/icon.svg", "web/public/brand/mathtutor.svg", "site/public/favicon.svg"]) {
  await save(target, svg);
}
const master = await png(1024);
await save("desktop/build/icon.png", master);
await save("web/public/brand/mathtutor.png", master);
const apple = await png(180);
await save("web/app/apple-icon.png", apple);
await save("site/public/apple-touch-icon.png", apple);

// ICO's directory points to PNG payloads, supported by the Windows versions we ship.
const sizes = [16, 24, 32, 48, 64, 128, 256];
const payloads = await Promise.all(sizes.map(png));
const directory = Buffer.alloc(6 + 16 * sizes.length);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(sizes.length, 4);
let offset = directory.length;
for (let i = 0; i < sizes.length; i++) {
  const entry = 6 + 16 * i;
  directory[entry] = directory[entry + 1] = sizes[i] % 256;
  directory.writeUInt16LE(1, entry + 4);
  directory.writeUInt16LE(32, entry + 6);
  directory.writeUInt32LE(payloads[i].length, entry + 8);
  directory.writeUInt32LE(offset, entry + 12);
  offset += payloads[i].length;
}
const ico = Buffer.concat([directory, ...payloads]);
await save("desktop/build/icon.ico", ico);
await save("web/app/favicon.ico", ico);

const temporary = await mkdtemp(path.join(tmpdir(), "mathtutor-brand-"));
try {
  const iconset = path.join(temporary, "MathTutor.iconset");
  await mkdir(iconset);
  for (const size of [16, 32, 128, 256, 512]) {
    await writeFile(path.join(iconset, `icon_${size}x${size}.png`), await png(size));
    await writeFile(path.join(iconset, `icon_${size}x${size}@2x.png`), await png(size * 2));
  }
  execFileSync("/usr/bin/iconutil", ["-c", "icns", iconset, "-o", path.join(root, "desktop/build/icon.icns")]);
} finally {
  await rm(temporary, { recursive: true, force: true });
}

const card = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#0f172a"/>
  <rect width="1200" height="8" fill="#1D4ED8"/>
  <text x="80" y="138" fill="#f8fafc" font-family="Arial, sans-serif" font-size="64" font-weight="700">MathTutor</text>
  <text x="80" y="200" fill="#93c5fd" font-family="Arial, sans-serif" font-size="28">Beyond Answers, Toward Real Understanding.</text>
  <g transform="translate(80 300) scale(6)" fill="none">${body}</g>
</svg>`;
await save("site/public/og.png", await sharp(Buffer.from(card)).png().toBuffer());
console.log("Generated shared MathTutor brand assets, browser icons and desktop icons.");
